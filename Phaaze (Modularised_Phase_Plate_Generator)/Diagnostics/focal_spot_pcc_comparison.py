# MAIN
# =============================================================================

def main() -> None:
    desired = load_2d_array(DESIRED_FOCAL_SPOT_FILE)
    extent_um = load_extent_um(COMMON_FOCAL_SPOT_EXTENT_FILE)

    focal_spot_files = {
        "Random phase plate (RPP)": RPP_FOCAL_SPOT_FILE,
        "Continuous phase plate (CPP)": CONTINUOUS_FOCAL_SPOT_FILE,
        "Distributed phase plate (DPP)": DISTRIBUTED_FOCAL_SPOT_FILE,
    }

    focal_spots = {
        name: load_2d_array(path)
        for name, path in focal_spot_files.items()
    }

    print("\nLoaded focal-spot shapes:")
    print(f"  Desired focal spot: {desired.shape}")
    for name, image in focal_spots.items():
        print(f"  {name}: {image.shape}")

    # Put every generated focal spot on the desired focal spot's grid.
    focal_spots = {
        name: resample_to_reference_grid(
            image,
            extent_um,
            desired.shape,
        )
        for name, image in focal_spots.items()
    }

    if PEAK_NORMALISE:
        desired = peak_normalise(desired)
        focal_spots = {
            name: peak_normalise(image)
            for name, image in focal_spots.items()
        }

    mask = build_comparison_mask(
        desired,
        extent_um,
        FOCAL_HALF_WIDTH_UM,
        REFERENCE_THRESHOLD,
    )

    results = []
    for name, image in focal_spots.items():
        pcc = pearson_correlation(image, desired, mask)
        results.append((name, pcc))

    results.sort(key=lambda item: item[1], reverse=True)

    print("\nPearson correlation against the desired focal spot:")
    for name, pcc in results:
        print(f"  {name:<34s} PCC = {pcc:.6f}")

    print("\nRanking:")
    for rank, (name, pcc) in enumerate(results, start=1):
        print(f"  {rank}. {name}: {pcc:.6f}")

    print(f"\nPixels included in comparison: {np.count_nonzero(mask):,}")

    if FOCAL_HALF_WIDTH_UM is None:
        print("Comparison region: complete saved focal plane")
    else:
        print(
            "Comparison region: "
            f"x, y = +/-{FOCAL_HALF_WIDTH_UM:.3f} um"
        )

    if REFERENCE_THRESHOLD is not None:
        print(
            "Desired-intensity threshold: "
            f"{REFERENCE_THRESHOLD:.3e} of peak"
        )

    if SAVE_RESULTS_CSV:
        with RESULTS_CSV_FILE.open("w", newline="", encoding="utf-8") as file:
            writer = csv.writer(file)
            writer.writerow(["Rank", "Phase plate", "PCC"])
            for rank, (name, pcc) in enumerate(results, start=1):
                writer.writerow([rank, name, f"{pcc:.10f}"])

        print(f"\nSaved results to:\n  {RESULTS_CSV_FILE}")


if __name__ == "__main__":
    main()
