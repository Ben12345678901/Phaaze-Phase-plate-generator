# =============================================================================
# DATA LOADING AND GRID HANDLING
# =============================================================================

def load_2d_array(path: Path) -> np.ndarray:
    """Load a finite two-dimensional NumPy array."""
    if not path.exists():
        raise FileNotFoundError(f"File does not exist:\n{path}")

    array = np.asarray(np.load(path), dtype=np.float64).squeeze()

    if array.ndim != 2:
        raise ValueError(
            f"Expected a 2-D array in {path.name}, but found shape {array.shape}"
        )

    if not np.isfinite(array).all():
        raise ValueError(f"{path.name} contains NaN or infinite values")

    return array


def load_extent_um(path: Path) -> tuple[float, float, float, float]:
    """Load [xmin, xmax, ymin, ymax] in micrometres."""
    if not path.exists():
        raise FileNotFoundError(f"Extent file does not exist:\n{path}")

    extent = np.asarray(np.load(path), dtype=np.float64).squeeze().ravel()

    if extent.size != 4:
        raise ValueError(
            f"Expected four extent values [xmin, xmax, ymin, ymax], "
            f"but found shape {extent.shape}"
        )

    xmin, xmax, ymin, ymax = map(float, extent)

    if not np.isfinite(extent).all():
        raise ValueError("The focal-spot extent contains NaN or infinite values")

    if xmax <= xmin or ymax <= ymin:
        raise ValueError(
            f"Invalid focal-spot extent: {[xmin, xmax, ymin, ymax]}"
        )

    return xmin, xmax, ymin, ymax


def peak_normalise(image: np.ndarray) -> np.ndarray:
    """Clip negative numerical noise and peak-normalise an intensity map."""
    image = np.clip(np.asarray(image, dtype=np.float64), 0.0, None)
    peak = float(np.max(image))

    if peak <= 0:
        raise ValueError("Cannot normalise an array whose peak is zero")

    return image / peak


def resample_to_reference_grid(
    image: np.ndarray,
    extent_um: tuple[float, float, float, float],
    reference_shape: tuple[int, int],
) -> np.ndarray:
    """Bilinearly resample an image onto the desired focal-spot grid.

    The same physical extent is assumed for all focal spots. If the array
    already has the desired shape, it is returned unchanged.
    """
    image = np.asarray(image, dtype=np.float64)

    if image.shape == reference_shape:
        return image.copy()

    xmin, xmax, ymin, ymax = extent_um

    source_y = np.linspace(ymin, ymax, image.shape[0])
    source_x = np.linspace(xmin, xmax, image.shape[1])

    target_y = np.linspace(ymin, ymax, reference_shape[0])
    target_x = np.linspace(xmin, xmax, reference_shape[1])

    # Interpolate in x for each source row.
    x_resampled = np.empty((image.shape[0], reference_shape[1]), dtype=np.float64)
    for row_index, row in enumerate(image):
        x_resampled[row_index] = np.interp(
            target_x,
            source_x,
            row,
            left=0.0,
            right=0.0,
        )

    # Interpolate in y for each target-grid column.
    output = np.empty(reference_shape, dtype=np.float64)
    for column_index in range(reference_shape[1]):
        output[:, column_index] = np.interp(
            target_y,
            source_y,
            x_resampled[:, column_index],
            left=0.0,
            right=0.0,
        )

    return output


def build_comparison_mask(
    reference: np.ndarray,
    extent_um: tuple[float, float, float, float],
    focal_half_width_um: float | None,
    reference_threshold: float | None,
) -> np.ndarray:
    """Build the physical-window and optional signal-threshold mask."""
    xmin, xmax, ymin, ymax = extent_um

    x_um = np.linspace(xmin, xmax, reference.shape[1])
    y_um = np.linspace(ymin, ymax, reference.shape[0])

    mask = np.ones(reference.shape, dtype=bool)

    if focal_half_width_um is not None:
        if focal_half_width_um <= 0:
            raise ValueError("FOCAL_HALF_WIDTH_UM must be positive or None")

        x_mask = np.abs(x_um) <= focal_half_width_um
        y_mask = np.abs(y_um) <= focal_half_width_um
        mask &= y_mask[:, None] & x_mask[None, :]

    if reference_threshold is not None:
        if not 0 <= reference_threshold < 1:
            raise ValueError("REFERENCE_THRESHOLD must lie in [0, 1)")
        mask &= reference >= reference_threshold

    if np.count_nonzero(mask) < 2:
        raise ValueError(
            "The selected comparison region contains fewer than two pixels"
        )

    return mask


# =============================================================================
# PEARSON CORRELATION
# =============================================================================

def pearson_correlation(
    test: np.ndarray,
    reference: np.ndarray,
    mask: np.ndarray,
) -> float:
    """Calculate the image PCC using the selected comparison pixels."""
    if test.shape != reference.shape:
        raise ValueError(
            f"Shape mismatch: test {test.shape}, reference {reference.shape}"
        )

    test_values = np.asarray(test[mask], dtype=np.float64)
    reference_values = np.asarray(reference[mask], dtype=np.float64)

    test_centered = test_values - np.mean(test_values)
    reference_centered = reference_values - np.mean(reference_values)

    denominator = (
        np.linalg.norm(test_centered)
        * np.linalg.norm(reference_centered)
    )

    if denominator == 0:
        raise ValueError(
            "PCC is undefined because one selected array is constant"
        )

    return float(np.dot(test_centered, reference_centered) / denominator)


